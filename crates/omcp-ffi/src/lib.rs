fn chunk_handshake(msg: &[u8], out: &mut Vec<Vec<u8>>) -> Result<(), FfiError> {
    let chunks: Vec<_> = msg.chunks(HANDSHAKE_CHUNK).collect();
    let total = u8::try_from(chunks.len()).map_err(|_| invalid("handshake too large"))?;
    for (i, c) in chunks.iter().enumerate() {
        let mut p = Vec::with_capacity(3 + c.len());
        p.extend_from_slice(&[PDU_HANDSHAKE, i as u8, total]);
        p.extend_from_slice(c);
        out.push(p);
    }
    Ok(())
}

#[uniffi::export]
impl MeshLink {
    /// Initiator: emit handshake message 1. Responder: no-op.
    pub fn start(&self) -> Result<LinkOutput, FfiError> {
        let mut st = self.lock();
        let mut out = LinkOutput::default();
        if let Role::Initiator(init) = &mut st.role {
            let node = &self.node;
            let m1 = init.write_message_1_with(|h| node.handshake_payload(h))?;
            chunk_handshake(&m1, &mut out.outgoing)?;
        }
        Ok(out)
    }

    /// Feed one PDU received from the peer (Inbox write or Outbox notify).
    pub fn on_pdu(&self, pdu: Vec<u8>) -> Result<LinkOutput, FfiError> {
        let mut st = self.lock();
        let mut out = LinkOutput::default();
        let (&kind, body) = pdu.split_first().ok_or_else(|| invalid("empty pdu"))?;
        match kind {
            PDU_HANDSHAKE => {
                if body.len() < 2 {
                    return Err(invalid("handshake pdu"));
                }
                let (idx, total) = (body[0], body[1]);
                if idx == 0 {
                    st.hs_buf.clear();
                    st.hs_total = total;
                } else if total != st.hs_total {
                    return Err(invalid("handshake chunk mismatch"));
                }
                st.hs_buf.extend_from_slice(&body[2..]);
                if idx + 1 == total {
                    let msg = std::mem::take(&mut st.hs_buf);
                    self.complete_handshake(&mut st, &msg, &mut out)?;
                }
            }
            PDU_LINK => {
                let peer = st.peer;
                let Role::Up(up) = &mut st.role else {
                    return Err(FfiError::State {
                        msg: "link fragment before handshake".into(),
                    });
                };
                let peer = peer.ok_or(FfiError::UnknownContact)?;
                if let Some(bytes) = up.reasm.push_frame(&mut up.link, body, Instant::now())? {
                    let env = EnvelopeV1::decode(&bytes)?;
                    let key = up.recv_key();
                    let (ct, plain) = open_app_envelope(&key, &peer, &env, &mut up.app_recv)?;
                    let plain = Zeroizing::new(plain);
                    let mut node = self.node.lock();
                    if !node.seen.check_and_insert(env.envelope_id, Instant::now())
                        && !node.mesh_seen(&env.envelope_id)
                    {
                        node.mesh_note_direct(env.envelope_id)?;
                        let from = (
                            out.file_progress.len(),
                            out.files.len(),
                            out.file_failures.len(),
                        );
                        Self::deliver(&mut node, peer, &env, ct, &plain, &mut out)?;
                        node.check_refetched(&mut out, from.1);
                        node.persist_file_events(&out, from, now_ms())?;
                    }
                    let replies = node.queues.get(&peer).is_some_and(|q| !q.is_empty());
                    drop(node);
                    if replies {
                        self.flush_locked(&mut st, &mut out)?;
                    }
                }
            }
            mesh::PDU_MESH => {
                let Role::Up(up) = &mut st.role else {
                    return Err(FfiError::State {
                        msg: "mesh fragment before handshake".into(),
                    });
                };
                if let Some(frame) = up
                    .mesh_reasm
                    .push_frame(&mut up.link, body, Instant::now())?
                {
                    // A malformed frame from a neighbour is dropped, not fatal.
                    let _ = self.mesh_frame(&frame, &mut out);
                }
                if let Role::Up(up) = &mut st.role {
                    self.drain_mesh(up, &mut out)?;
                }
            }
            mesh::PDU_MLS_SETUP => {
                let peer = st.peer.ok_or(FfiError::UnknownContact)?;
                let Role::Up(up) = &mut st.role else {
                    return Err(FfiError::State {
                        msg: "MLS setup before handshake".into(),
                    });
                };
                if let Some(frame) =
                    up.setup_reasm
                        .push_frame(&mut up.link, body, Instant::now())?
                {
                    // A failed setup is retried on the next link; not fatal.
                    let _ = self.mls_setup_frame(&peer, &frame);
                }
                if let Role::Up(up) = &mut st.role {
                    self.drain_mesh(up, &mut out)?;
                }
            }
            _ => return Err(invalid("unknown pdu kind")),
        }
        Self::fill(&st, &mut out);
        self.relay_links(&mut out);
        Ok(out)
    }

    /// Send text now if established, otherwise queue it on the node.
    pub fn send_text(&self, text: String) -> Result<LinkOutput, FfiError> {
        let mut st = self.lock();
        let mut out = LinkOutput::default();
        let peer = st.peer.ok_or(FfiError::UnknownContact)?;
        match &mut st.role {
            Role::Up(up) => {
                if text.len() > MAX_TEXT_BYTES {
                    return Err(invalid("text too long"));
                }
                let q = Queued {
                    envelope_id: random_id16()?,
                    created_ms: now_ms(),
                    inner: Zeroizing::new(core_burn::encode_app(
                        None,
                        &AppContent::Text(text.clone()),
                    )?),
                    control: false,
                };
                Self::seal_into(&self.node, up, &q, &mut out)?;
                self.node.lock().db().put_message(&MessageRec {
                    id: q.envelope_id,
                    peer,
                    mine: true,
                    time_ms: q.created_ms,
                    status: st::STATUS_SENT,
                    text,
                    mime: None,
                    burn: None,
                    burn_state: st::BURN_NONE,
                    burn_at_ms: None,
                    file: None,
                })?;
            }
            _ => {
                drop(st);
                return OmcpNode {
                    inner: self.node.clone(),
                }
                .queue_text(hex::encode(peer), text)
                .map(|_| LinkOutput::default());
            }
        }
        Self::fill(&st, &mut out);
        Ok(out)
    }

    /// Flush any queued texts for this peer (e.g. after queueing elsewhere).
    pub fn flush(&self) -> Result<LinkOutput, FfiError> {
        // Community messages produced while handling PDUs (founder Welcome,
        // gossip) are queued here, outside the node lock.
        OmcpNode {
            inner: self.node.clone(),
        }
        .drain_community_outbox();
        let mut st = self.lock();
        let mut out = LinkOutput::default();
        self.flush_locked(&mut st, &mut out)?;
        Self::fill(&st, &mut out);
        self.relay_links(&mut out);
        Ok(out)
    }

    pub fn is_established(&self) -> bool {
        matches!(self.lock().role, Role::Up(_))
    }

    /// Opaque handle of this link (see [`LinkOutput::relay_links`]).
    pub fn handle(&self) -> u64 {
        self.handle
    }

    /// Tear down; the peer no longer counts as nearby.
    pub fn shutdown(&self) {
        let mut st = self.lock();
        st.role = Role::Closed;
        self.mesh_link_down();
        let mut node = self.node.lock();
        node.links_up.remove(&self.handle);
        if let Some(peer) = st.peer {
            if !node.links_up.values().any(|p| *p == peer) {
                let _ = node.pause_transfers(&peer);
            }
        }
    }
}

impl MeshLink {
    fn lock(&self) -> MutexGuard<'_, LinkState> {
        self.state.lock().unwrap_or_else(|p| p.into_inner())
    }

    fn fill(st: &LinkState, out: &mut LinkOutput) {
        out.established = matches!(st.role, Role::Up(_));
        out.peer_contact_id = st.peer.map(hex::encode);
    }

    /// Route one decrypted message: text, burn content into the shredding store, or `OPENED`.
    pub(crate) fn deliver(
        node: &mut NodeState,
        peer: [u8; 32],
        env: &EnvelopeV1,
        ct: u8,
        plain: &[u8],
        out: &mut LinkOutput,
    ) -> Result<(), FfiError> {
        let mut rt = ReceivedText {
            contact_id: hex::encode(peer),
            text: String::new(),
            created_ms: env.created_ms,
            envelope_id_hex: hex::encode(env.envelope_id),
            burn: None,
            mime: None,
        };
        let received = |text: &str, mime: Option<String>, burn: Option<&BurnHeader>| MessageRec {
            id: env.envelope_id,
            peer,
            mine: false,
            time_ms: env.created_ms,
            status: st::STATUS_RECEIVED,
            text: text.into(),
            mime,
            burn: burn.map(|h| h.encode().to_vec()),
            burn_state: if burn.is_some() {
                st::BURN_UNOPENED
            } else {
                st::BURN_NONE
            },
            burn_at_ms: None,
            file: None,
        };
        if ct == CONTENT_TYPE_TEXT_PLAIN {
            rt.text = String::from_utf8(plain.to_vec()).map_err(|_| invalid("utf8"))?;
            node.db().put_message(&received(&rt.text, None, None))?;
            out.received.push(rt);
            return Ok(());
        }
        let (burn, content) = core_burn::decode_app(plain)?;
        match (burn, content) {
            (_, AppContent::Opened(r)) => {
                let Some(meta) = node.burn_meta.get(&r.msg_id) else {
                    return Ok(());
                };
                if meta.peer != peer {
                    return Ok(()); // only the recipient may open it
                }
                let media = meta.mime.is_some();
                let shredded = node
                    .burn_out
                    .on_remote_opened(&r.msg_id, r.opened_ms, media);
                let burn_at_ms = node.burn_out.burn_at(&r.msg_id);
                node.persist_burn(&r.msg_id)?;
                if shredded {
                    node.burn_message_now(&r.msg_id)?;
                } else {
                    node.update_message(&r.msg_id, |m| {
                        m.burn_state = st::BURN_OPEN;
                        m.burn_at_ms = burn_at_ms;
                    })?;
                }
                out.opened.push(OpenedEvent {
                    contact_id: hex::encode(peer),
                    msg_id_hex: hex::encode(r.msg_id),
                    opened_ms: r.opened_ms,
                    shredded,
                    burn_at_ms,
                });
            }
            (None, AppContent::FileMeta(b)) => files::on_offer(&mut node.files, peer, &b, out),
            (None, AppContent::FileChunk(b)) => files::on_chunk(&mut node.files, peer, &b, out),
            (Some(_), AppContent::FileMeta(_) | AppContent::FileChunk(_)) => {
                return Err(invalid("burn file"))
            }
            (None, AppContent::MediaControl(c)) => node.on_media_control(peer, c, out)?,
            (Some(_), AppContent::MediaControl(_)) => return Err(invalid("burn control")),
            (None, AppContent::Text(t)) => {
                node.db().put_message(&received(&t, None, None))?;
                rt.text = t;
                out.received.push(rt);
            }
            (None, AppContent::Media { mime, bytes }) if mime == private_group::COMMUNITY_MIME => {
                // Community control / live announcement; no chat row.
                node.on_community_msg(peer, &bytes)?;
            }
            (None, AppContent::Media { mime, bytes }) if mime == omcp_core::live::INVITE_MIME => {
                // Live invite: stream key over the E2EE chat; no chat row.
                node.on_live_invite(peer, &bytes, out)?;
            }
            (None, AppContent::Media { mime, bytes })
                if mime == omcp_core::live::signal::SIGNAL_MIME =>
            {
                // Live WebRTC signal (0x50); hosts relay to the tree neighbour.
                // Forwards go out on the next `live_take_signals()` poll.
                let fwd = node.on_live_signal(peer, &bytes);
                node.mesh.live.pending_fwd.extend(fwd);
            }
            (None, AppContent::Media { mime, .. }) => {
                // TODO(M5.x): non-burn media goes through the chunked file path.
                node.db()
                    .put_message(&received("", Some(mime.clone()), None))?;
                rt.mime = Some(mime);
                out.received.push(rt);
            }
            (Some(h), c) => {
                let (body, mime) = match &c {
                    AppContent::Text(t) => (t.as_bytes(), None),
                    AppContent::Media { mime, bytes } => (bytes.as_slice(), Some(mime.clone())),
                    AppContent::Opened(_)
                    | AppContent::FileMeta(_)
                    | AppContent::FileChunk(_)
                    | AppContent::MediaControl(_) => unreachable!(),
                };
                node.burn_in
                    .insert(env.envelope_id, h, body, env.created_ms)?;
                node.burn_meta.insert(
                    env.envelope_id,
                    BurnMeta {
                        peer,
                        mime: mime.clone(),
                    },
                );
                node.persist_burn(&env.envelope_id)?;
                node.db()
                    .put_message(&received("", mime.clone(), Some(&h)))?;
                rt.burn = Some(BurnSpec::from_header(&h));
                rt.mime = mime;
                out.received.push(rt);
            }
        }
        Ok(())
    }

    fn seal_into(
        node: &NodeInner,
        up: &mut Established,
        q: &Queued,
        out: &mut LinkOutput,
    ) -> Result<(), FfiError> {
        let env = seal_inner_envelope(
            &up.send_key(),
            &node.peer_id,
            q.envelope_id,
            &q.inner,
            q.created_ms,
            &mut up.app_send,
            TTL_HOPS,
        )?;
        // Remember our own envelope so a gossip echo is not shown as received.
        node.lock()
            .seen
            .check_and_insert(env.envelope_id, Instant::now());
        let bytes = env.encode()?;
        for f in fragment_and_seal(
            &mut up.link,
            &bytes,
            random_frag_id()?,
            LINK_FRAGMENT_PAYLOAD,
        )? {
            let mut p = Vec::with_capacity(1 + f.len());
            p.push(PDU_LINK);
            p.extend_from_slice(&f);
            out.outgoing.push(p);
        }
        Ok(())
    }

    fn flush_locked(&self, st: &mut LinkState, out: &mut LinkOutput) -> Result<(), FfiError> {
        let (Some(peer), Role::Up(up)) = (st.peer, &mut st.role) else {
            return Ok(());
        };
        let pending: Vec<Queued> = self
            .node
            .lock()
            .queues
            .remove(&peer)
            .map(Vec::from)
            .unwrap_or_default();
        for q in &pending {
            Self::seal_into(&self.node, up, q, out)?;
            if !q.control {
                out.flushed += 1;
            }
            let mut node = self.node.lock();
            node.db().delete_outbox(&q.envelope_id)?;
            node.mesh_cancel_own(&q.envelope_id)?;
            if !q.control {
                node.set_status(&q.envelope_id, st::STATUS_SENT)?;
            }
        }
        // Then the active file transfer, a few chunks per call.
        let mut node = self.node.lock();
        let Some(q) = node.files.out.get_mut(&peer) else {
            drop(node);
            return self.drain_mesh(up, out);
        };
        let mut batch: Vec<Queued> = Vec::new();
        let from = out.file_progress.len();
        if let Some(f) = q.front_mut() {
            if f.link != Some(self.handle) {
                f.link = Some(self.handle);
                f.cursor = 0;
                batch.push(Queued {
                    envelope_id: random_id16()?,
                    created_ms: now_ms(),
                    inner: f.offer.clone(),
                    control: true,
                });
            }
            for _ in 0..files::FILE_CHUNKS_PER_FLUSH {
                let Some(c) = f.chunks.get(f.cursor) else {
                    break;
                };
                batch.push(Queued {
                    envelope_id: random_id16()?,
                    created_ms: now_ms(),
                    inner: c.clone(),
                    control: true,
                });
                f.cursor += 1;
            }
            out.file_progress.push(f.progress(&peer));
            if f.cursor >= f.chunks.len() {
                let id = f.id;
                q.pop_front();
                node.db().delete_out_file(&id)?;
            }
        }
        out.more_pending = node.files.out.get(&peer).is_some_and(|q| !q.is_empty());
        node.persist_file_events(
            out,
            (from, out.files.len(), out.file_failures.len()),
            now_ms(),
        )?;
        drop(node);
        for m in &batch {
            Self::seal_into(&self.node, up, m, out)?;
        }
        self.drain_mesh(up, out)
    }

    fn complete_handshake(
        &self,
        st: &mut LinkState,
        msg: &[u8],
        out: &mut LinkOutput,
    ) -> Result<(), FfiError> {
        let role = std::mem::replace(&mut st.role, Role::Closed);
        let peer_cert: core_device::DeviceCert;
        let mut applied = false;
        let up = match role {
            Role::Initiator(mut init) => {
                let (payload, h, keys) = init.read_message_2_bound(msg)?;
                let expected = st.peer.ok_or(FfiError::UnknownContact)?;
                let dh = self
                    .node
                    .lock()
                    .contacts
                    .get(&expected)
                    .map(|c| c.dh)
                    .ok_or(FfiError::UnknownContact)?;
                // (c) device binding: certificate for this session's key + signature over h.
                let cert = core_device::verify_handshake_payload(&payload, &h, &dh)?;
                let peer = self.node.lock().resolve_peer(expected, &cert)?;
                st.peer = Some(peer);
                peer_cert = cert;
                Established {
                    link: LinkSession::initiator(&keys),
                    keys,
                    initiator: true,
                    reasm: FragmentReassembler::default(),
                    mesh_reasm: FragmentReassembler::default(),
                    setup_reasm: FragmentReassembler::default(),
                    app_send: 0,
                    app_recv: 0,
                }
            }
            Role::Responder(mut resp) => {
                // §22.8(5): an initiator that still has our previous device
                // key reaches us through it during the overlap.
                let mut use_prev = false;
                let (payload, h) = match resp.read_message_1_bound(msg) {
                    Ok(v) => v,
                    Err(e) => {
                        let Some(id) = self.node.prev_identity(now_ms()) else {
                            return Err(e.into());
                        };
                        let mut r2 = Box::new(HybridResponder::new(id));
                        let v = r2.read_message_1_bound(msg).map_err(|_| e)?;
                        resp = r2;
                        use_prev = true;
                        v
                    }
                };
                let rs = resp.remote_static().ok_or(FfiError::UnknownContact)?;
                // (c) device binding; then find the contact by PeerID (or a legacy
                // contact by its X25519 id). Unknown initiators are refused
                // (beta requires mutual QR add).
                let cert = core_device::verify_handshake_payload(&payload, &h, &rs)?;
                let peer = {
                    let mut node = self.node.lock();
                    let expected = if node.contacts.contains_key(&cert.peer_id) {
                        cert.peer_id
                    } else if node.contacts.get(&rs).is_some_and(|c| c.legacy(&rs)) {
                        rs
                    } else {
                        return Err(FfiError::UnknownContact);
                    };
                    let peer = node.resolve_peer(expected, &cert)?;
                    // RS1/RS2 before answering: a superseded device key fails here.
                    node.apply_peer_cert(peer, &cert, now_ms(), out)?;
                    peer
                };
                applied = true;
                let node = &self.node;
                let (m2, keys) = resp.write_message_2_with(|h| {
                    if use_prev {
                        match node.prev_device().as_ref() {
                            Some((d, _)) => d.handshake_payload(h),
                            None => node.handshake_payload(h),
                        }
                    } else {
                        node.handshake_payload(h)
                    }
                })?;
                chunk_handshake(&m2, &mut out.outgoing)?;
                peer_cert = cert;
                st.peer = Some(peer);
                Established {
                    link: LinkSession::responder(&keys),
                    keys,
                    initiator: false,
                    reasm: FragmentReassembler::default(),
                    mesh_reasm: FragmentReassembler::default(),
                    setup_reasm: FragmentReassembler::default(),
                    app_send: 0,
                    app_recv: 0,
                }
            }
            other => {
                st.role = other;
                return Err(FfiError::State {
                    msg: "unexpected handshake message".into(),
                });
            }
        };
        if let (Some(p), false) = (st.peer, applied) {
            // RS1: the contact's device decides about the restore notice.
            self.node
                .lock()
                .apply_peer_cert(p, &peer_cert, now_ms(), out)?;
        }
        st.role = Role::Up(Box::new(up));
        if let Some(p) = st.peer {
            let mut node = self.node.lock();
            node.links_up.insert(self.handle, p);
            // CB3: ask the partner again for every missing-media placeholder.
            node.request_missing_media(&p, out)?;
            drop(node);
            self.mesh_link_up(&p)?;
        }
        self.flush_locked(st, out)
    }
}

