/// Errors surfaced to Kotlin.
#[derive(Debug, thiserror::Error, uniffi::Error)]
pub enum FfiError {
    #[error("invalid input: {msg}")]
    Invalid { msg: String },
    #[error("crypto/protocol error: {msg}")]
    Protocol { msg: String },
    #[error("unknown contact")]
    UnknownContact,
    #[error("bad state: {msg}")]
    State { msg: String },
    #[error("wrong backup password")]
    WrongBackupPassword,
    #[error("backup format v{version} is newer than this app supports")]
    BackupTooNew { version: u8 },
    #[error("file too large: {size} bytes exceeds {max}")]
    FileTooLarge { size: u64, max: u64 },
    /// Local store failure: wrong storage key, newer schema, other identity, I/O.
    #[error("local storage: {msg}")]
    Storage { msg: String },
    /// QR verification failed: the code doesn't match this contact's current
    /// identity + device key (e.g. a QR from before a restore, RS2).
    #[error("safety number doesn't match")]
    VerificationFailed,
}

impl From<omcp_core::OmcpError> for FfiError {
    fn from(e: omcp_core::OmcpError) -> Self {
        match e {
            omcp_core::OmcpError::FileTooLarge { size, max } => {
                return FfiError::FileTooLarge { size, max }
            }
            omcp_core::OmcpError::BackupAuth => return FfiError::WrongBackupPassword,
            omcp_core::OmcpError::BackupTooNew(version) => {
                return FfiError::BackupTooNew { version }
            }
            omcp_core::OmcpError::Store(_) | omcp_core::OmcpError::StoreAuth => {
                return FfiError::Storage { msg: e.to_string() }
            }
            _ => {}
        }
        FfiError::Protocol { msg: e.to_string() }
    }
}

pub(crate) fn invalid(msg: &str) -> FfiError {
    FfiError::Invalid { msg: msg.into() }
}

