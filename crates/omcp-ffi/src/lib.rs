fn random_id16() -> Result<[u8; 16], FfiError> {
    let mut id = [0u8; 16];
    getrandom_fill(&mut id)?;
    Ok(id)
}

fn getrandom_fill(b: &mut [u8]) -> Result<(), FfiError> {
    getrandom::getrandom(b).map_err(|_| FfiError::Protocol {
        msg: "getrandom".into(),
    })
}

pub(crate) fn parse_msg_id(h: &str) -> Result<[u8; 16], FfiError> {
    let v = hex::decode(h).map_err(|_| invalid("msg id hex"))?;
    v.try_into().map_err(|_| invalid("msg id length"))
}

pub(crate) struct NodeInner {
    seed: Zeroizing<[u8; 32]>,
    /// PeerID = BLAKE2b-256(identity public key) (v0.1.4a).
    peer_id: [u8; 32],
    /// Our pre-v0.1.4a id (X25519 from the seed): what legacy contacts know us by.
    legacy_id: [u8; 32],
    name: String,
    state: Mutex<NodeState>,
    /// This installation's device key (RS1). Never locked while holding `state`
    /// is required; lock order is `state` → `device`.
    device: Mutex<OwnDevice>,
    /// The device key replaced by [`OmcpNode::rotate_device_key`], kept until
    /// the given time (§22.8(5): 7-day overlap). Lock order: after `device`.
    prev_device: Mutex<Option<(OwnDevice, u64)>>,
}

impl NodeInner {
    fn lock(&self) -> MutexGuard<'_, NodeState> {
        self.state.lock().unwrap_or_else(|p| p.into_inner())
    }
    /// This device's Noise static identity (per-device X25519, certified).
    fn identity(&self) -> Result<StaticIdentity, FfiError> {
        Ok(self.device().static_identity()?)
    }
    fn dh_public(&self) -> [u8; 32] {
        self.device().cert().map(|c| c.dh).unwrap_or([0; 32])
    }
    fn device(&self) -> MutexGuard<'_, OwnDevice> {
        self.device.lock().unwrap_or_else(|p| p.into_inner())
    }
    fn prev_device(&self) -> MutexGuard<'_, Option<(OwnDevice, u64)>> {
        self.prev_device.lock().unwrap_or_else(|p| p.into_inner())
    }
    /// The previous device's Noise identity while its overlap lasts.
    fn prev_identity(&self, now: u64) -> Option<StaticIdentity> {
        let g = self.prev_device();
        g.as_ref()
            .filter(|(_, until)| now < *until)
            .and_then(|(d, _)| d.static_identity().ok())
    }
    fn device_public(&self) -> [u8; 32] {
        self.device().public().unwrap_or([0; 32])
    }
    /// Noise handshake payload: device certificate + signature over `h`.
    fn handshake_payload(&self, h: &[u8]) -> omcp_core::error::Result<Vec<u8>> {
        self.device().handshake_payload(h)
    }
}

pub(crate) fn parse_id(hex_id: &str) -> Result<[u8; 32], FfiError> {
    let v = hex::decode(hex_id).map_err(|_| invalid("contact id hex"))?;
    v.try_into().map_err(|_| invalid("contact id length"))
}

/// Safety number v2 (identity + current device keys, RS2) once both device keys
/// are known; v1 (identity keys only) with a peer on an older app.
pub(crate) fn contact_info(node: &NodeInner, id: &[u8; 32], c: &Contact) -> ContactInfo {
    let mine = node.device_public();
    // A legacy contact still knows us by our legacy id (both sides switch to
    // PeerIDs in the same handshake), so both compute the same number.
    let me = if c.legacy(id) {
        node.legacy_id
    } else {
        node.peer_id
    };
    let safety_number = match c.device.current_key() {
        Some(theirs) => safety::safety_number_v2(&me, Some(&mine), id, Some(&theirs)),
        None => safety::safety_number(&me, id),
    };
    ContactInfo {
        contact_id: hex::encode(id),
        display_name: c.name.clone(),
        safety_number,
        verified: c.verified,
        restored_badge: c.device.badge_active(now_ms()),
        restored_at_ms: c.device.restored_at_ms,
        restored_unverified: c.device.restored_unverified && !c.verified,
    }
}

pub(crate) fn now_ms() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0)
}

impl OmcpNode {
    fn seal(
        &self,
        secret: backup::BackupSecret<'_>,
        device_hint: &str,
        created_at_ms: u64,
    ) -> Result<Vec<u8>, FfiError> {
        let contacts = self
            .inner
            .lock()
            .contacts
            .iter()
            .map(|(id, c)| backup::BackupContact {
                peer_id: *id,
                name: c.name.clone(),
                verified: c.verified,
                dh: (!c.legacy(id)).then(|| c.dh.to_vec()),
            })
            .collect();
        // Message history moved to the chat backup (v0.1.4, see `chatbackup`);
        // the Argon2id identity backup carries identity, contacts and name only.
        let contents = backup::BackupContents {
            entropy: Zeroizing::new(*self.inner.seed),
            contacts,
            display_name: Some(self.inner.name.clone()).filter(|n| !n.is_empty()),
            history: None,
        };
        Ok(backup::seal_backup(
            &contents,
            secret,
            created_at_ms,
            device_hint,
        )?)
    }
}

/// Local node: identity, contacts, offline queue.
#[derive(uniffi::Object)]
pub struct OmcpNode {
    inner: Arc<NodeInner>,
}

#[uniffi::export]
impl OmcpNode {
    /// Load (or restore) the identity from its 24-word recovery phrase.
    /// Everything stays in memory (lost on restart). See [`Self::open`].
    #[uniffi::constructor]
    pub fn from_phrase(phrase: String, display_name: String) -> Result<Arc<Self>, FfiError> {
        let key = st::generate_storage_key()?;
        Self::build(phrase, display_name, Store::open_in_memory(&key)?)
    }

    /// Load the identity and open (or create) its encrypted local store at
    /// `db_path`, restoring contacts, verification state, chats, messages, file
    /// metadata, pending queue and burn state. `storage_key` (32 bytes) comes
    /// from the Android Keystore / iOS Keychain; a wrong key fails with `Storage`.
    #[uniffi::constructor]
    pub fn open(
        phrase: String,
        display_name: String,
        db_path: String,
        storage_key: Vec<u8>,
    ) -> Result<Arc<Self>, FfiError> {
        let key = Zeroizing::new(storage_key);
        let key: Zeroizing<[u8; 32]> = Zeroizing::new(
            key[..]
                .try_into()
                .map_err(|_| invalid("storage key must be 32 bytes"))?,
        );
        let db = Store::open(std::path::Path::new(&db_path), &key)?;
        Self::build(phrase, display_name, db)
    }
}

impl OmcpNode {
    fn build(phrase: String, display_name: String, db: Store) -> Result<Arc<Self>, FfiError> {
        let seed = recovery::phrase_to_seed(&phrase)?;
        let peer_id = core_device::peer_id_from_seed(&seed)?;
        let legacy_id = core_device::legacy_dh_public(&seed)?;
        // v0.1.4a: stores bound to the legacy X25519 id move to the PeerID.
        let legacy_install = db.rebind_owner(&legacy_id, &peer_id)?;
        let device =
            chatbackup::load_or_create_device(&db, &seed, peer_id, legacy_install, now_ms())?;
        let prev_device = db
            .get_meta::<(OwnDevice, u64)>(chatbackup::META_PREV_DEVICE)
            .ok()
            .flatten()
            .filter(|(d, until)| now_ms() < *until && d.valid_for(&peer_id));
        let node = Arc::new(Self {
            inner: Arc::new(NodeInner {
                seed,
                peer_id,
                legacy_id,
                name: display_name,
                device: Mutex::new(device),
                prev_device: Mutex::new(prev_device),
                state: Mutex::new(NodeState {
                    contacts: HashMap::new(),
                    queues: HashMap::new(),
                    burn_in: BurnStore::default(),
                    burn_out: BurnStore::default(),
                    burn_meta: HashMap::new(),
                    links_up: HashMap::new(),
                    next_link: 1,
                    seen: SeenCache::default(),
                    files: files::FileState::default(),
                    db,
                    pending_backup: None,
                    mesh: mesh::MeshState::new(now_ms()),
                }),
            }),
        });
        node.inner.lock().load(now_ms())?;
        Ok(node)
    }
}

#[uniffi::export]
impl OmcpNode {
    pub fn identity(&self) -> IdentityInfo {
        IdentityInfo {
            peer_id_hex: hex::encode(self.inner.peer_id),
            display_name: self.inner.name.clone(),
        }
    }

    /// The 24-word phrase (Settings › Backup › View phrase; gate behind device auth).
    pub fn recovery_phrase(&self) -> Result<String, FfiError> {
        Ok(recovery::seed_to_phrase(&self.inner.seed)?.to_string())
    }

    /// Encrypted backup blob (identity + contacts + verification state).
    /// The plaintext phrase never leaves this function unencrypted.
    pub fn create_backup(
        &self,
        password: String,
        device_hint: String,
        created_at_ms: u64,
    ) -> Result<Vec<u8>, FfiError> {
        self.seal(
            backup::BackupSecret::Password(&password),
            &device_hint,
            created_at_ms,
        )
    }

    /// iCloud "No password" mode: the blob is sealed under a 256-bit key that the app
    /// keeps in iCloud Keychain (synchronizable). See [`generate_backup_key`].
    pub fn create_backup_with_key(
        &self,
        key: Vec<u8>,
        device_hint: String,
        created_at_ms: u64,
    ) -> Result<Vec<u8>, FfiError> {
        let key = platform_key(key)?;
        self.seal(
            backup::BackupSecret::PlatformKey(&key),
            &device_hint,
            created_at_ms,
        )
    }

    /// Contact QR payload (v0.1.4a):
    /// `omcp:3:<PeerID>:<identity key>:<device key>:<X25519 key>:<display name>`.
    /// The device and X25519 keys make the code change after a restore (RS2).
    pub fn qr_payload(&self) -> String {
        let cert = self.inner.device().cert().ok();
        format!(
            "{QR_PREFIX_V3}{}:{}:{}:{}:{}",
            hex::encode(self.inner.peer_id),
            hex::encode(cert.as_ref().map(|c| c.identity_sign).unwrap_or([0; 32])),
            hex::encode(self.inner.device_public()),
            hex::encode(self.inner.dh_public()),
            self.inner.name
        )
    }

    /// 13-byte BLE discovery advertisement (PROTOCOL §8.2). Carries the PeerID
    /// prefix; an install migrated from before v0.1.4a keeps its legacy X25519
    /// key and advertises that, so legacy contacts still find it.
    pub fn advertisement(&self) -> Vec<u8> {
        let dh = self.inner.dh_public();
        let id = if dh == self.inner.legacy_id {
            dh
        } else {
            self.inner.peer_id
        };
        DiscoveryAdvertisement::new(1, &id, capabilities::PQ)
            .encode()
            .to_vec()
    }

    /// Parse a QR and compute its safety number without saving anything.
    pub fn preview_contact_from_qr(&self, payload: String) -> Result<ContactPreview, FfiError> {
        let q = self.parse_qr(&payload)?;
        let (id, name, qr_dev) = (q.id, q.name.clone(), q.device);
        let st = self.inner.lock();
        let known = st.contacts.get(&id);
        let mismatch_with = st
            .contacts
            .iter()
            .find(|(k, c)| **k != id && c.name == name)
            .map(|(k, c)| self.info(k, c));
        let contact = match known {
            Some(c) => self.info(&id, c),
            None => self.info(
                &id,
                &Contact {
                    name,
                    verified: false,
                    device: ContactDevice {
                        current: qr_dev.map(|d| d.to_vec()),
                        ..ContactDevice::default()
                    },
                    dh: q.dh,
                },
            ),
        };
        Ok(ContactPreview {
            contact,
            already_known: known.is_some(),
            mismatch_with,
        })
    }

    /// Add a contact from a scanned QR payload.
    pub fn add_contact_from_qr(&self, payload: String) -> Result<ContactInfo, FfiError> {
        let q = self.parse_qr(&payload)?;
        let id = q.id;
        let mut st = self.inner.lock();
        let c = st.contacts.entry(id).or_insert(Contact {
            name: q.name.clone(),
            verified: false,
            device: ContactDevice::default(),
            dh: q.dh,
        });
        if c.device.current.is_none() && c.device.superseded.is_empty() {
            // Pin the device key from the QR; the handshake certificate must match it.
            c.device.current = q.device.map(|d| d.to_vec());
            c.dh = q.dh;
        }
        if c.device.identity_sign.is_none() {
            c.device.identity_sign = q.identity_sign.map(|k| k.to_vec());
        }
        let info = self.info(&id, c);
        st.persist_contact(&id)?;
        Ok(info)
    }
}

/// A parsed contact QR code.
pub(crate) struct QrInfo {
    /// PeerID (v3) or the legacy X25519 id (v1/v2).
    pub id: [u8; 32],
    pub name: String,
    pub device: Option<[u8; 32]>,
    pub identity_sign: Option<[u8; 32]>,
    /// X25519 Noise key to dial.
    pub dh: [u8; 32],
}

fn key32(h: &str, what: &str) -> Result<[u8; 32], FfiError> {
    hex::decode(h)
        .ok()
        .and_then(|v| v.try_into().ok())
        .ok_or_else(|| invalid(what))
}

impl OmcpNode {
    /// v3 codes carry PeerID + identity, device and X25519 keys; v2 (legacy id +
    /// device key) and v1 (legacy id) are still accepted as legacy contacts.
    pub(crate) fn parse_qr(&self, payload: &str) -> Result<QrInfo, FfiError> {
        let p = payload.trim();
        let (q, hex_id) = if let Some(r) = p.strip_prefix(QR_PREFIX_V3) {
            let mut it = r.splitn(5, ':');
            let (Some(pid), Some(ik), Some(dev), Some(dh)) =
                (it.next(), it.next(), it.next(), it.next())
            else {
                return Err(invalid("QR fields"));
            };
            let id = parse_id(pid)?;
            let ik = key32(ik, "QR identity key")?;
            if core_device::peer_id_from_identity(&ik) != id {
                return Err(invalid("QR identity key doesn't match PeerID"));
            }
            (
                QrInfo {
                    id,
                    name: it.next().unwrap_or("").to_string(),
                    device: Some(key32(dev, "QR device key")?),
                    identity_sign: Some(ik),
                    dh: key32(dh, "QR X25519 key")?,
                },
                pid.to_string(),
            )
        } else {
            let (rest, v2) = match (p.strip_prefix(QR_PREFIX_V2), p.strip_prefix(QR_PREFIX)) {
                (Some(r), _) => (r, true),
                (None, Some(r)) => (r, false),
                _ => return Err(invalid("not an OMCP contact QR")),
            };
            let (hex_id, rest) = rest.split_once(':').unwrap_or((rest, ""));
            let (dev, name) = if v2 {
                let (d, n) = rest.split_once(':').unwrap_or((rest, ""));
                (Some(key32(d, "QR device key")?), n)
            } else {
                (None, rest)
            };
            let id = parse_id(hex_id)?;
            (
                QrInfo {
                    id,
                    name: name.to_string(),
                    device: dev,
                    identity_sign: None,
                    dh: id,
                },
                hex_id.to_string(),
            )
        };
        if q.id == self.inner.peer_id || q.id == self.inner.legacy_id {
            return Err(invalid("cannot add yourself"));
        }
        let name = if q.name.is_empty() {
            format!("Peer {}", &hex_id[..8.min(hex_id.len())])
        } else {
            q.name.chars().take(64).collect()
        };
        Ok(QrInfo { name, ..q })
    }
}

#[uniffi::export]
impl OmcpNode {
    /// Restore a contact from app storage (no QR parse). Without a key the id
    /// is taken as a legacy X25519 id.
    pub fn restore_contact(
        &self,
        contact_id: String,
        display_name: String,
        verified: bool,
    ) -> Result<(), FfiError> {
        self.restore_contact_with_key(contact_id, display_name, verified, None)
    }

    /// Restore a contact from a backup with its X25519 key (`BackupContact::dh_hex`).
    pub fn restore_contact_with_key(
        &self,
        contact_id: String,
        display_name: String,
        verified: bool,
        dh_hex: Option<String>,
    ) -> Result<(), FfiError> {
        let id = parse_id(&contact_id)?;
        let dh = match dh_hex {
            Some(h) => key32(&h, "contact X25519 key")?,
            None => id,
        };
        let mut st = self.inner.lock();
        st.contacts.insert(
            id,
            Contact {
                name: display_name,
                verified,
                device: ContactDevice::default(),
                dh,
            },
        );
        st.persist_contact(&id)
    }

    pub fn contacts(&self) -> Vec<ContactInfo> {
        let st = self.inner.lock();
        let mut v: Vec<_> = st.contacts.iter().map(|(id, c)| self.info(id, c)).collect();
        v.sort_by(|a, b| a.display_name.cmp(&b.display_name));
        v
    }

    pub fn set_verified(&self, contact_id: String, verified: bool) -> Result<(), FfiError> {
        let id = parse_id(&contact_id)?;
        let mut st = self.inner.lock();
        let c = st.contacts.get_mut(&id).ok_or(FfiError::UnknownContact)?;
        c.verified = verified;
        st.persist_contact(&id)
    }

    /// Contact whose PeerID starts with this 6-byte prefix (from an advertisement).
    pub fn contact_for_prefix(&self, prefix_hex: String) -> Option<String> {
        let st = self.inner.lock();
        st.contacts
            .iter()
            .find(|(id, c)| {
                hex::encode(&id[..6]) == prefix_hex || hex::encode(&c.dh[..6]) == prefix_hex
            })
            .map(|(id, _)| hex::encode(id))
    }

    /// Queue a text for a contact; it is sent when a link to them is up.
    pub fn queue_text(&self, contact_id: String, text: String) -> Result<(), FfiError> {
        self.queue_message(contact_id, text, None).map(|_| ())
    }

    /// Queue a text, optionally burn after read. The `burn` header travels inside the
    /// encrypted inner message. Returns the message (envelope) id, hex.
    pub fn queue_message(
        &self,
        contact_id: String,
        text: String,
        burn: Option<BurnSpec>,
    ) -> Result<String, FfiError> {
        if text.len() > MAX_TEXT_BYTES {
            return Err(invalid("text too long"));
        }
        self.queue_app(&contact_id, AppContent::Text(text), burn, None, false)
    }

    /// Queue a (small, ≤ 16 KiB in the beta) media item, e.g. a view-once photo.
    pub fn queue_media(
        &self,
        contact_id: String,
        mime: String,
        bytes: Vec<u8>,
        burn: Option<BurnSpec>,
    ) -> Result<String, FfiError> {
        if bytes.len() > MAX_TEXT_BYTES {
            return Err(invalid("media too large for the beta link"));
        }
        let m = Some(mime.clone());
        self.queue_app(
            &contact_id,
            AppContent::Media { mime, bytes },
            burn,
            m,
            false,
        )
    }

    /// Open a received burn message. Returns its content exactly once (None afterwards,
    /// or once burned/expired) and queues an encrypted `OPENED` receipt to the sender.
    pub fn open_burn(
        &self,
        msg_id_hex: String,
        now_ms: u64,
    ) -> Result<Option<BurnContent>, FfiError> {
        let id = parse_msg_id(&msg_id_hex)?;
        let mut st = self.inner.lock();
        let Some(meta) = st.burn_meta.get(&id) else {
            return Ok(None);
        };
        let (peer, mime) = (meta.peer, meta.mime.clone());
        if !st.burn_in.is_live(&id) {
            return Ok(None);
        }
        let Opened::Content {
            body,
            receipt,
            burn_at_ms,
        } = st.burn_in.open(&id, now_ms)?
        else {
            return Ok(None);
        };
        let inner = core_burn::encode_app(None, &AppContent::Opened(receipt))?;
        let q = Queued {
            envelope_id: random_id16()?,
            created_ms: now_ms,
            inner: Zeroizing::new(inner),
            control: true,
        };
        st.persist_queued(&peer, &q)?;
        mesh::submit_own(&self.inner, &mut st, &peer, &q, None)?;
        st.queues.entry(peer).or_default().push_back(q);
        st.persist_burn(&id)?;
        st.update_message(&id, |m| {
            m.burn_state = st::BURN_OPEN;
            m.burn_at_ms = burn_at_ms;
        })?;
        let (text, bytes) = if mime.is_some() {
            (String::new(), body.to_vec())
        } else {
            (String::from_utf8_lossy(&body).into_owned(), Vec::new())
        };
        Ok(Some(BurnContent {
            text,
            bytes,
            mime,
            burn_at_ms,
        }))
    }

    /// Viewer closed: burn the opened message now.
    pub fn close_burn(&self, msg_id_hex: String) -> Result<(), FfiError> {
        let id = parse_msg_id(&msg_id_hex)?;
        let mut st = self.inner.lock();
        st.burn_in.close(&id);
        if !st.burn_in.is_live(&id) {
            st.persist_burn(&id)?;
            st.burn_message_now(&id)?;
        }
        Ok(())
    }

    /// Run timers and unread expiry on both stores. Returns ids that were crypto-shredded.
    pub fn tick_burn(&self, now_ms: u64) -> Vec<String> {
        let mut st = self.inner.lock();
        let mut out = st.burn_in.tick(now_ms);
        out.extend(st.burn_out.tick(now_ms));
        for id in &out {
            // Best effort: a failure here is retried by `load` on the next start.
            let _ = st.db().delete_burn(id);
            let _ = st.burn_message_now(id);
        }
        out.iter().map(hex::encode).collect()
    }

    /// Whether any copy (sent or received) of this burn message still exists on this node.
    pub fn burn_is_live(&self, msg_id_hex: String) -> bool {
        let Ok(id) = parse_msg_id(&msg_id_hex) else {
            return false;
        };
        let st = self.inner.lock();
        st.burn_in.is_live(&id) || st.burn_out.is_live(&id)
    }

    /// Queue a file (≤ 50 MB, checked before any encryption) for a contact. It is
    /// encrypted into 64 KiB chunks now and sent when a link to them is up; one
    /// transfer per contact is active at a time, others wait in line.
    pub fn queue_file(
        &self,
        contact_id: String,
        name: String,
        mime: String,
        bytes: Vec<u8>,
    ) -> Result<FileOffer, FfiError> {
        let id = parse_id(&contact_id)?;
        check_file_size(bytes.len() as u64)?;
        if !self.inner.lock().contacts.contains_key(&id) {
            return Err(FfiError::UnknownContact);
        }
        let tid = random_id16()?;
        let f = files::build_outgoing(tid, &name, &mime, &bytes)?;
        let mut st = self.inner.lock();
        st.persist_out_file(&id, &f)?;
        let msg = MessageRec {
            id: tid,
            peer: id,
            mine: true,
            time_ms: now_ms(),
            status: st::STATUS_QUEUED,
            text: String::new(),
            mime: None,
            burn: None,
            burn_state: st::BURN_NONE,
            burn_at_ms: None,
            file: Some(st::FileRec {
                name: name.clone(),
                mime: mime.clone(),
                size: f.size,
                state: st::FILE_QUEUED,
                done_bytes: 0,
                local_path: None,
                hash: Some(blake3::hash(&bytes).as_bytes().to_vec()),
                locator: Some(tid.to_vec()),
            }),
        };
        st.db().put_message(&msg)?;
        st.keep_sent(&msg, &bytes, now_ms())?;
        let offer = FileOffer {
            transfer_id_hex: hex::encode(tid),
            contact_id,
            name,
            mime,
            size: f.size,
            num_chunks: f.total,
        };
        st.files.out.entry(id).or_default().push_back(f);
        Ok(offer)
    }

    /// Cancel an outbound transfer (queued or in progress). Returns whether it existed.
    pub fn cancel_file(&self, transfer_id_hex: String) -> bool {
        let Ok(tid) = parse_msg_id(&transfer_id_hex) else {
            return false;
        };
        let mut st = self.inner.lock();
        let _ = st.db().delete_out_file(&tid);
        let _ = st.db().delete_message(&tid);
        for q in st.files.out.values_mut() {
            if let Some(i) = q.iter().position(|f| f.id == tid) {
                q.remove(i);
                return true;
            }
        }
        st.files.incoming.remove(&tid).is_some()
    }

    /// Outbound file transfers (active + queued) for a contact.
    pub fn files_pending_for(&self, contact_id: String) -> u32 {
        let Ok(id) = parse_id(&contact_id) else {
            return 0;
        };
        self.inner
            .lock()
            .files
            .out
            .get(&id)
            .map_or(0, |q| q.len() as u32)
    }

    pub fn queued_for(&self, contact_id: String) -> u32 {
        let Ok(id) = parse_id(&contact_id) else {
            return 0;
        };
        self.inner
            .lock()
            .queues
            .get(&id)
            .map_or(0, |q| q.iter().filter(|m| !m.control).count() as u32)
    }

    /// Aggregate path status for the banner. Gateway transport is not wired in
    /// the beta, so `Gateway`/`Mixed` are not produced yet.
    pub fn path_status(&self) -> PathStatus {
        let st = self.inner.lock();
        let queued: usize = st
            .queues
            .values()
            .map(|q| q.iter().filter(|m| !m.control).count())
            .sum();
        let mut peers: Vec<_> = st.links_up.values().collect();
        peers.sort();
        peers.dedup();
        PathStatus {
            nearby_peers: peers.len() as u32,
            queued_count: queued as u32,
            path: if queued == 0 && !peers.is_empty() {
                PathKind::Mesh
            } else {
                PathKind::Queued
            },
        }
    }

    /// Chats with persisted messages, most recent first.
    pub fn chats(&self) -> Result<Vec<ChatSummary>, FfiError> {
        let mut v: Vec<_> = self
            .inner
            .lock()
            .db()
            .chats()?
            .into_iter()
            .map(|c| ChatSummary {
                contact_id: hex::encode(c.peer),
                last_ms: c.last_ms,
                last_read_ms: c.last_read_ms,
            })
            .collect();
        v.sort_by_key(|a| std::cmp::Reverse(a.last_ms));
        Ok(v)
    }

    /// Persisted messages of one chat, oldest first.
    pub fn stored_messages(&self, contact_id: String) -> Result<Vec<StoredMessage>, FfiError> {
        let id = parse_id(&contact_id)?;
        Ok(self
            .inner
            .lock()
            .db()
            .messages(&id)?
            .iter()
            .map(persist::to_stored)
            .collect())
    }

    /// Record where the app saved a verified received file (None = couldn't save).
    pub fn set_received_file_path(
        &self,
        transfer_id_hex: String,
        local_path: Option<String>,
    ) -> Result<(), FfiError> {
        let id = parse_msg_id(&transfer_id_hex)?;
        self.inner.lock().update_message(&id, |m| {
            if let Some(f) = m.file.as_mut() {
                f.state = if local_path.is_some() {
                    st::FILE_RECEIVED
                } else {
                    st::FILE_FAILED
                };
                f.local_path = local_path;
            }
        })
    }

    pub fn mark_chat_read(&self, contact_id: String, now_ms: u64) -> Result<(), FfiError> {
        let id = parse_id(&contact_id)?;
        let st = self.inner.lock();
        let mut c = st.db().chat(&id)?.unwrap_or(st::ChatRec {
            peer: id,
            last_ms: 0,
            last_read_ms: 0,
        });
        c.last_read_ms = c.last_read_ms.max(now_ms);
        Ok(st.db().put_chat(&c)?)
    }

    /// Import the `history` of a decrypted backup ([`RestoredBackup::history`]).
    pub fn restore_history(&self, history: Vec<u8>) -> Result<(), FfiError> {
        let history = Zeroizing::new(history);
        let mut st = self.inner.lock();
        st.db().import_history(&history)?;
        st.load(now_ms())
    }

    /// New link as Noise initiator (we are the GATT central dialling a contact).
    pub fn open_initiator_link(&self, contact_id: String) -> Result<Arc<MeshLink>, FfiError> {
        let id = parse_id(&contact_id)?;
        let dh = match self.inner.lock().contacts.get(&id) {
            Some(c) => c.dh,
            None => return Err(FfiError::UnknownContact),
        };
        let init = HybridInitiator::new(self.inner.identity()?, &dh)?;
        Ok(self.new_link(Role::Initiator(Box::new(init)), Some(id)))
    }

    /// Replace this installation's device key (Noise static + device
    /// certificate). The previous key keeps answering handshakes for
    /// [`DEVICE_KEY_OVERLAP_MS`] (§22.8(5)); 1:1 MLS groups and envelopes in
    /// flight are unaffected because they are bound to the MLS epoch.
    pub fn rotate_device_key(&self) -> Result<(), FfiError> {
        let now = now_ms();
        let st = self.inner.lock();
        let fresh = OwnDevice::generate(&self.inner.seed, now, None)?;
        let old = std::mem::replace(&mut *self.inner.device(), fresh.clone());
        let prev = (old, now.saturating_add(DEVICE_KEY_OVERLAP_MS));
        st.db().put_meta(chatbackup::META_DEVICE, &fresh)?;
        st.db().put_meta(chatbackup::META_PREV_DEVICE, &prev)?;
        *self.inner.prev_device() = Some(prev);
        Ok(())
    }

    /// New link as Noise responder (we are the GATT peripheral).
    pub fn open_responder_link(&self) -> Result<Arc<MeshLink>, FfiError> {
        let resp = HybridResponder::new(self.inner.identity()?);
        Ok(self.new_link(Role::Responder(Box::new(resp)), None))
    }
}

impl OmcpNode {
    /// `control` = not a user message (no chat row; e.g. a Live invite).
    pub(crate) fn queue_app(
        &self,
        contact_id: &str,
        content: AppContent,
        burn: Option<BurnSpec>,
        mime: Option<String>,
        control: bool,
    ) -> Result<String, FfiError> {
        let id = parse_id(contact_id)?;
        let header = burn.map(|b| b.header()).transpose()?;
        let inner = core_burn::encode_app(header.as_ref(), &content)?;
        let envelope_id = random_id16()?;
        let now = now_ms();
        let mut st = self.inner.lock();
        if !st.contacts.contains_key(&id) {
            return Err(FfiError::UnknownContact);
        }
        if let Some(h) = header {
            let body: &[u8] = match &content {
                AppContent::Text(t) => t.as_bytes(),
                AppContent::Media { bytes, .. } => bytes,
                AppContent::Opened(_)
                | AppContent::FileMeta(_)
                | AppContent::FileChunk(_)
                | AppContent::MediaControl(_) => &[],
            };
            st.burn_out.insert(envelope_id, h, body, now)?;
            st.burn_meta.insert(
                envelope_id,
                BurnMeta {
                    peer: id,
                    mime: mime.clone(),
                },
            );
            st.persist_burn(&envelope_id)?;
        }
        let text = match (&content, header) {
            (AppContent::Text(t), None) => t.clone(),
            _ => String::new(),
        };
        if !control {
            st.db().put_message(&MessageRec {
                id: envelope_id,
                peer: id,
                mine: true,
                time_ms: now,
                status: st::STATUS_QUEUED,
                text,
                mime,
                burn: header.map(|h| h.encode().to_vec()),
                burn_state: if header.is_some() {
                    st::BURN_UNOPENED
                } else {
                    st::BURN_NONE
                },
                burn_at_ms: None,
                file: None,
            })?;
        }
        let q = Queued {
            envelope_id,
            created_ms: now,
            inner: Zeroizing::new(inner),
            control,
        };
        st.persist_queued(&id, &q)?;
        mesh::submit_own(&self.inner, &mut st, &id, &q, header.as_ref())?;
        st.queues.entry(id).or_default().push_back(q);
        Ok(hex::encode(envelope_id))
    }

    fn info(&self, id: &[u8; 32], c: &Contact) -> ContactInfo {
        contact_info(&self.inner, id, c)
    }

    fn new_link(&self, role: Role, peer: Option<[u8; 32]>) -> Arc<MeshLink> {
        let mut st = self.inner.lock();
        let handle = st.next_link;
        st.next_link += 1;
        Arc::new(MeshLink {
            node: self.inner.clone(),
            handle,
            state: Mutex::new(LinkState {
                role,
                peer,
                hs_buf: Vec::new(),
                hs_total: 0,
            }),
        })
    }
}

